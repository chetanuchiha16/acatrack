@student_report_bp.route("/students", methods=["GET"])
def list_students():
    try:
        students = sorted(_load_student_data().keys())
        return jsonify({"students": students})
    except FileNotFoundError as e:
        return jsonify({"error": str(e)}), 404

@student_report_bp.route("/report/<student_name>", methods=["GET"])
def get_student_report(student_name):
    try:
        student_data_map = _load_student_data()
        matched_name = next((n for n in student_data_map if n.lower() == student_name.lower()), None)
        if not matched_name:
            return jsonify({"error": "Student not found"}), 404

        student_data = student_data_map[matched_name]
        summary = _calculate_summary(student_data["semester_results"])

        return jsonify({
            "student_name": matched_name,
            "summary": summary,
            "semester_results": student_data["semester_results"]
        })
    except FileNotFoundError as e:
        return jsonify({"error": str(e)}), 404

@student_report_bp.route("/report/<student_name>/pdf", methods=["GET"])
def download_pdf_report(student_name):
    try:
        student_data_map = _load_student_data()
        matched_name = next((n for n in student_data_map if n.lower() == student_name.lower()), None)
        if not matched_name:
            return jsonify({"error": "Student not found"}), 404

        student_data = student_data_map[matched_name]
        pdf_buffer = generate_pdf_report(student_data)
        return send_file(
            pdf_buffer,
            mimetype="application/pdf",
            as_attachment=True,
            download_name=f"{matched_name}_Semester_Report.pdf"
        )
    except FileNotFoundError as e:
        return jsonify({"error": str(e)}), 404
